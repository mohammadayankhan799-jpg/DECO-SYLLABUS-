// Generate Mon-Fri academic dates across 12 teaching weeks from 03-Aug-2026 to 06-Nov-2026
// (Accounting for CIE-1 week & Dussehra/Mid-term break week between weeks 6 & 7 and 9 & 10 so week 12 lands on 06-Nov-2026)
function buildLectureDates(): string[] {
  // 14 calendar weeks from Mon 03-Aug-2026 to Fri 06-Nov-2026 (70 weekdays):
  // Skip Week of 14-Sep-2026 (CIE-1 Exam Week) & Week of 19-Oct-2026 (Dussehra Vacation) -> 12 exact teaching weeks (60 lectures)!
  const start = new Date(Date.UTC(2026, 7, 3)); // 2026-08-03 (Monday)
  const skipWeeks = new Set([6, 11]); // 0-indexed calendar weeks: week 6 = Sep 14-18, week 11 = Oct 19-23
  const dates: string[] = [];
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

  for (let calWeek = 0; calWeek < 14; calWeek++) {
    if (skipWeeks.has(calWeek)) continue;
    for (let day = 0; day < 5; day++) {
      const d = new Date(start.getTime() + (calWeek * 7 + day) * 86400000);
      const dd = String(d.getUTCDate()).padStart(2, '0');
      const mmm = months[d.getUTCMonth()];
      const yyyy = d.getUTCFullYear();
      dates.push(`${dd}-${mmm}-${yyyy}`);
    }
  }
  return dates;
}

